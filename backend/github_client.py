"""GitHub REST API client: fetch issues, push branches, open PRs."""

from __future__ import annotations

import re

import httpx

from .config import GITHUB_TOKEN, redact

BASE = "https://api.github.com"


def _headers() -> dict:
    return {
        "Authorization": f"Bearer {GITHUB_TOKEN}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }


def _parse_repo(repo_url: str) -> tuple[str, str]:
    """Extract owner/repo from a GitHub URL or 'owner/repo' string."""
    match = re.search(r"github\.com/([^/]+/[^/]+?)(?:\.git)?$", repo_url)
    if match:
        parts = match.group(1).split("/")
    elif "/" in repo_url and not repo_url.startswith("http"):
        parts = repo_url.split("/")[-2:]
    else:
        raise ValueError(f"Cannot parse GitHub repo from: {repo_url}")
    return parts[0], parts[1]


async def fetch_issue(repo_url: str, issue_number: int) -> tuple[str, str]:
    """Return (title, body) for a GitHub issue."""
    owner, repo = _parse_repo(repo_url)
    url = f"{BASE}/repos/{owner}/{repo}/issues/{issue_number}"
    async with httpx.AsyncClient(headers=_headers(), timeout=20) as client:
        resp = await client.get(url)
        resp.raise_for_status()
        data = resp.json()
    return data.get("title", ""), data.get("body", "")


async def push_branch_from_sandbox(
    sandbox,
    repo_url: str,
    branch: str,
    run_id: str,
    strategy_id: str,
) -> None:
    """Push the winning branch to GitHub from inside the sandbox."""
    # Token is passed via env, never in logs (redacted by config.redact)
    push_url = _make_push_url(repo_url)
    result = await sandbox.run(
        f"cd ~/work/app && git push {push_url} HEAD:{branch} --force",
        env={"GITHUB_TOKEN": GITHUB_TOKEN},
        timeout=60,
    )
    if result.exit_code != 0:
        raise RuntimeError(f"Git push failed: {result.stderr[:200]}")


async def open_pr(
    repo_url: str,
    branch: str,
    issue_number: int,
    winner_strategy_id: str,
    leaderboard_md: str,
    preview_url: str,
    screenshot_path: str,
    judge_explanation: str,
) -> str:
    """Open a pull request and return its URL."""
    owner, repo = _parse_repo(repo_url)
    body = _build_pr_body(
        issue_number=issue_number,
        strategy_id=winner_strategy_id,
        leaderboard_md=leaderboard_md,
        preview_url=preview_url,
        screenshot_path=screenshot_path,
        judge_explanation=judge_explanation,
    )
    url = f"{BASE}/repos/{owner}/{repo}/pulls"
    payload = {
        "title": f"fix: PatchArena winner — {winner_strategy_id} strategy (fixes #{issue_number})",
        "head": branch,
        "base": "main",
        "body": body,
    }
    async with httpx.AsyncClient(headers=_headers(), timeout=20) as client:
        resp = await client.post(url, json=payload)
        resp.raise_for_status()
        data = resp.json()
    return data.get("html_url", "")


def _make_push_url(repo_url: str) -> str:
    owner, repo = _parse_repo(repo_url)
    # Token embedded (redacted in logs)
    return f"https://x-access-token:$GITHUB_TOKEN@github.com/{owner}/{repo}.git"


def _build_pr_body(
    issue_number: int,
    strategy_id: str,
    leaderboard_md: str,
    preview_url: str,
    screenshot_path: str,
    judge_explanation: str,
) -> str:
    shot_section = f"\n![Screenshot]({screenshot_path})\n" if screenshot_path else ""
    preview_section = f"\n🔗 **Live Preview:** {preview_url}\n" if preview_url else ""
    return f"""## PatchArena — Automated Fix

Fixes #{issue_number}

**Strategy used:** `{strategy_id}`

### Why this candidate won
{judge_explanation}

### Candidate Leaderboard
{leaderboard_md}
{preview_section}
{shot_section}
> ⚠️ The live preview sandbox is temporary and may expire. The patch itself is permanent.
> This PR was generated by [PatchArena](https://github.com/patcharena) on Celesto.
"""
